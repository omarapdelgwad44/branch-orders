export const LANGUAGES = [
  { code: 'ar', label: 'العربية' },
  { code: 'en', label: 'English' }
];

let currentLang = localStorage.getItem('bo.lang') || 'ar';

export function getLang() {
  return currentLang;
}

export function setLang(code) {
  if (!DICTS[code]) code = 'ar';
  currentLang = code;
  localStorage.setItem('bo.lang', code);
  document.documentElement.lang = code;
  document.documentElement.dir = code === 'ar' ? 'rtl' : 'ltr';
  document.title = t('app.name') + ' — ' + t('app.tagline');
}

export function errorText(err) {
  const code = err && err.code ? String(err.code) : '';
  const key = code ? 'err.' + code : 'msg.error';
  const dict = DICTS[currentLang] || DICTS.en;
  if (dict[key] !== undefined) return dict[key];
  if (DICTS.en[key] !== undefined) return DICTS.en[key];
  return t('msg.error');
}

export function t(key, vars) {
  const dict = DICTS[currentLang] || DICTS.en;
  let s = dict[key] !== undefined ? dict[key] : (DICTS.en[key] !== undefined ? DICTS.en[key] : key);
  if (vars) {
    Object.keys(vars).forEach((k) => {
      s = s.split('{{' + k + '}}').join(vars[k]);
    });
  }
  return s;
}

export function fmtDate(iso) {
  if (!iso) return t('common.none');
  const d = new Date(iso);
  if (isNaN(d.getTime())) return iso;
  try {
    return new Intl.DateTimeFormat(currentLang === 'ar' ? 'ar-EG' : 'en-GB', {
      dateStyle: 'medium',
      timeStyle: 'short'
    }).format(d);
  } catch (e) {
    return iso;
  }
}

export function fmtNum(n) {
  const v = Number(n || 0);
  try {
    return new Intl.NumberFormat(currentLang === 'ar' ? 'ar-EG' : 'en-US').format(isNaN(v) ? 0 : v);
  } catch (e) {
    return String(v);
  }
}

